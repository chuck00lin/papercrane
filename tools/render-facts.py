#!/usr/bin/env python3
"""Compile manuscript/facts-map.yaml + reality/facts/ into manuscript/facts.tex (invariant I3).

Usage: python3 tools/render-facts.py
Every key in facts-map.yaml becomes \\fact{key}. Unknown or unfrozen fact ids fail the build.
Precision applies to numeric values; strings and dates are emitted verbatim; tables emit
their relative path (for \\input or a table-rendering macro of your own).
"""
import json, sys
from datetime import datetime
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
HEADER = r"""%% GENERATED by tools/render-facts.py — do not edit. %s
%% \fact{key} expands to the value declared in manuscript/facts-map.yaml.
\makeatletter
\newcommand{\fact}[1]{\@ifundefined{fact@#1}{\PackageError{papercrane}{Unknown fact '#1'}{}}{\csname fact@#1\endcsname}}
\makeatother
"""


def frozen():
    out = {}
    for p in sorted((ROOT / "reality" / "facts").rglob("*.facts.json")):
        for f in json.load(open(p)).get("facts", []):
            out[f["id"]] = f
    return out


def tex_escape(s):
    return str(s).replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("%", r"\%").replace("&", r"\&").replace("#", r"\#")


def main():
    fm = yaml.safe_load(open(ROOT / "manuscript" / "facts-map.yaml")) or {}
    facts = frozen()
    lines, errors = [], []
    for key, spec in (fm.get("facts") or {}).items():
        fid = spec.get("id")
        f = facts.get(fid)
        if f is None:
            errors.append(f"{key}: fact {fid!r} is not frozen")
            continue
        v, kind = f["value"], f["kind"]
        if kind in ("metric", "count") and isinstance(v, (int, float)):
            prec = int(spec.get("precision", 0 if kind == "count" else 3))
            text = f"{v:.{prec}f}" if prec > 0 else f"{round(v):d}"
        else:
            text = tex_escape(v)
        lines.append(f"\\expandafter\\def\\csname fact@{key}\\endcsname{{{text}}}  % {fid}")
    if errors:
        for e in errors:
            print(f"[render-facts] {e}", file=sys.stderr)
        sys.exit(1)
    out = ROOT / "manuscript" / "facts.tex"
    out.write_text(HEADER % datetime.now().isoformat(timespec="seconds") + "\n".join(lines) + "\n")
    print(f"[render-facts] wrote {out.relative_to(ROOT)} with {len(lines)} fact(s)")


if __name__ == "__main__":
    main()
