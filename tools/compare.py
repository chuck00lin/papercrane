#!/usr/bin/env python3
"""Leaderboard across runs.
  python3 tools/compare.py --experiment EXP-001-slug [--facts a,b] [--out experiments/EXP-001-slug/COMPARE.md]
  python3 tools/compare.py --fact height_r2           # one fact name across all experiments
Superseded values are shown in parentheses. Rows are ordered by run id; the variant column
is what makes an A/B series readable."""
import argparse, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _facts import ROOT, runs, frozen_facts, split_id  # noqa: E402


def fmt(f, superseded):
    v = f["value"]
    s = f"{v:.4g}" if isinstance(v, float) else str(v)
    if f.get("unit"): s += f" {f['unit']}"
    return f"({s})" if f["id"] in superseded else s


def md_table(header, rows):
    w = [max(len(str(x)) for x in col) for col in zip(header, *rows)] if rows else [len(h) for h in header]
    line = lambda r: "| " + " | ".join(str(x).ljust(w[i]) for i, x in enumerate(r)) + " |"
    return "\n".join([line(header), "|" + "|".join("-" * (x + 2) for x in w) + "|"] + [line(r) for r in rows])


def by_experiment(exp, names=None):
    facts, superseded = frozen_facts()
    mine = [f for f in facts.values() if f["_experiment"] == exp]
    if not mine:
        return f"no frozen facts for {exp}"
    cols = names or sorted({f["name"] for f in mine if f["kind"] in ("metric", "count")})
    rs = runs(exp)
    rows = []
    for run in sorted({f["_run"] for f in mine}):
        r = rs.get(run, {})
        cells = [run, r.get("variant", "-"), r.get("baseline_run", "-"), (r.get("code_commit") or "")[:8]]
        for n in cols:
            f = facts.get(f"{exp}.{run}.{n}")
            cells.append(fmt(f, superseded) if f else "-")
        rows.append(cells)
    return md_table(["run", "variant", "baseline", "commit"] + cols, rows)


def by_fact(name):
    facts, superseded = frozen_facts()
    rows = [[f["_experiment"], f["_run"], runs(f["_experiment"]).get(f["_run"], {}).get("variant", "-"),
             fmt(f, superseded), f.get("n", "-")]
            for f in sorted(facts.values(), key=lambda f: f["id"]) if f["name"] == name]
    return md_table(["experiment", "run", "variant", name, "n"], rows) if rows else f"no frozen fact named {name}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--experiment"); ap.add_argument("--fact"); ap.add_argument("--facts"); ap.add_argument("--out")
    a = ap.parse_args()
    if not (a.experiment or a.fact):
        ap.error("pass --experiment or --fact")
    t = by_experiment(a.experiment, a.facts.split(",") if a.facts else None) if a.experiment else by_fact(a.fact)
    print(t)
    if a.out:
        Path(a.out).write_text(f"# Leaderboard\n\nGENERATED by tools/compare.py; do not edit.\n\n{t}\n")
        print(f"[compare] wrote {a.out}")


if __name__ == "__main__":
    main()
